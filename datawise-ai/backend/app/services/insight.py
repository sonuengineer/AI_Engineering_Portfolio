"""Verifier + insight. Every number in the insight is computed in Python from the returned rows,
and each statement carries provenance (columns + row indexes). Nothing is generated by a model.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from app.schemas.api import ChartSpec, Provenance
from app.schemas.plan import QueryPlan
from app.semantic.layer import DIMENSIONS, METRICS

_NON_ADDITIVE_FOR_ORDERS = {"product", "category", "supplier"}


@dataclass
class InsightResult:
    text: str | None
    provenance: list[Provenance] = field(default_factory=list)
    chart: ChartSpec = field(default_factory=lambda: ChartSpec(type="table"))
    issues: list[str] = field(default_factory=list)


def fmt_value(metric: str, v: Any) -> str:
    if v is None:
        return "n/a"
    f = METRICS[metric].fmt
    x = float(v)
    if f == "currency":
        return f"${x:,.2f}"
    if f == "percent":
        return f"{x * 100:.1f}%"
    if f == "days":
        return f"{x:.1f} days"
    return f"{x:,.0f}" if x == int(x) else f"{x:,.2f}"


def fmt_period(dim: str, v: Any) -> str:
    s = str(v)
    if len(s) < 10:
        return s
    y, m = s[:4], int(s[5:7])
    if dim == "month":
        return f"{y}-{m:02d}"
    if dim == "quarter":
        return f"{y}-Q{(m - 1) // 3 + 1}"
    if dim == "year":
        return y
    return s


def _additive(metric: str, dims: list[str]) -> bool:
    if metric in ("revenue", "units_sold", "sessions"):
        return True
    if metric == "order_count":
        return not any(d in _NON_ADDITIVE_FOR_ORDERS for d in dims)
    return False


def verify(plan: QueryPlan, columns: list[str], rows: list[list[Any]]) -> list[str]:
    issues: list[str] = []
    expected = list(plan.dimensions) + list(plan.metrics)
    if columns != expected:
        issues.append(f"result columns {columns} do not match plan {expected}")
        return issues
    for ri, r in enumerate(rows):
        for ci, m in enumerate(plan.metrics, start=len(plan.dimensions)):
            v = r[ci]
            if v is not None and not isinstance(v, int | float):
                issues.append(f"row {ri} metric {m} is not numeric")
    return issues


def build_insight(plan: QueryPlan, columns: list[str], rows: list[list[Any]], truncated: bool) -> InsightResult:
    issues = verify(plan, columns, rows)
    if issues:
        return InsightResult(text=None, issues=issues)
    period = f" ({plan.time_range.label or plan.time_range.start.isoformat()})" if plan.time_range else ""
    m0 = plan.metrics[0]
    mi = len(plan.dimensions)
    label = METRICS[m0].label

    if not rows:
        return InsightResult(text=f"No data matched this question{period}.", chart=ChartSpec(type="table"))

    dims = plan.dimensions
    if not dims:
        parts = [f"{METRICS[m].label}{period}: {fmt_value(m, rows[0][mi + k])}" for k, m in enumerate(plan.metrics)]
        return InsightResult(
            text=". ".join(parts) + ".",
            provenance=[Provenance(columns=list(plan.metrics), row_indexes=[0], note="single aggregate row")],
            chart=ChartSpec(type="table"),
        )

    d0 = dims[0]
    is_time = DIMENSIONS[d0].is_time
    series = dims[1] if len(dims) > 1 else None
    chart = ChartSpec(type="line" if is_time else "bar", x=d0, y=list(plan.metrics), series=series)
    if len(rows) == 1:
        chart = ChartSpec(type="table")

    values = [(i, r[mi]) for i, r in enumerate(rows) if r[mi] is not None]
    if not values:
        return InsightResult(text=f"All {label.lower()} values are empty{period}.", chart=chart)

    def name(i: int) -> str:
        r = rows[i]
        parts = [fmt_period(d, r[k]) if DIMENSIONS[d].is_time else str(r[k]) for k, d in enumerate(dims)]
        return " / ".join(parts)

    hi_i, hi_v = max(values, key=lambda t: t[1])
    lo_i, lo_v = min(values, key=lambda t: t[1])
    sentences: list[str] = []
    prov: list[Provenance] = []
    total = sum(v for _, v in values)
    additive = _additive(m0, dims)

    if is_time and series is None:
        first_i, first_v = values[0]
        last_i, last_v = values[-1]
        change = ""
        if first_v not in (0, None) and len(values) > 1:
            pct = (last_v - first_v) / abs(first_v) * 100
            change = f" ({pct:+.1f}%)"
        if len(values) > 1:
            sentences.append(f"{label} went from {fmt_value(m0, first_v)} in {name(first_i)} to "
                             f"{fmt_value(m0, last_v)} in {name(last_i)}{change}")
            prov.append(Provenance(columns=[d0, m0], row_indexes=[first_i, last_i], note="first vs last period"))
        sentences.append(f"Peak: {name(hi_i)} at {fmt_value(m0, hi_v)}; lowest: {name(lo_i)} at "
                         f"{fmt_value(m0, lo_v)}")
        prov.append(Provenance(columns=[d0, m0], row_indexes=[hi_i, lo_i], note="max and min period"))
        if additive:
            sentences.append(f"Total over {len(values)} periods: {fmt_value(m0, total)}")
            prov.append(Provenance(columns=[m0], row_indexes=[i for i, _ in values], note="sum of all rows"))
    else:
        top_sentence = f"Highest {label.lower()}: {name(hi_i)} at {fmt_value(m0, hi_v)}"
        if additive and total:
            top_sentence += f" ({hi_v / total * 100:.1f}% of the {len(values)} rows shown)"
        sentences.append(top_sentence)
        prov.append(Provenance(columns=[*dims, m0], row_indexes=[hi_i], note="max row"))
        if len(values) > 1:
            sentences.append(f"Lowest: {name(lo_i)} at {fmt_value(m0, lo_v)}")
            prov.append(Provenance(columns=[*dims, m0], row_indexes=[lo_i], note="min row"))
        if additive and len(values) > 1:
            sentences.append(f"Total across rows shown: {fmt_value(m0, total)}")
            prov.append(Provenance(columns=[m0], row_indexes=[i for i, _ in values], note="sum of all rows"))
    text = ". ".join(sentences) + f"{period and ' ' + period.strip()}."
    if truncated:
        text += " Results were truncated at the row limit."
    return InsightResult(text=text, provenance=prov, chart=chart)
